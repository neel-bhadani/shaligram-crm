<script setup>
import { ref, computed, watch } from 'vue'
import { useForm } from '@inertiajs/vue3'
import Modal from '@/Components/Modal.vue'
import FormField from '@/Components/FormField.vue'
import CopyField from '@/Components/CopyField.vue'
import ConfirmDialog from '@/Components/ConfirmDialog.vue'

/*
 | 11za WhatsApp chatbot configuration.
 |
 | The same two halves as the Facebook modal: where the leads land, which the
 | admin chooses here, and the webhook URL and API key, which they copy into
 | 11za. There are no tokens to type — the API key is generated by the CRM on
 | the first save and stays the same after that.
 |
 | "Projects by 11za tag" is Facebook's lead-form table for 11za tags: the same
 | rows (lead_form_routes), keyed by the tag normalised the way the server
 | normalises incoming tags — see LeadFormRoute::normaliseTag().
 */
const props = defineProps({
  show: Boolean,
  card: Object,
  options: Object,
})

const emit = defineEmits(['close'])

const form = useForm({
  default_project_id: '',
  assign_to_user_id: '',
  is_active: false,
  tags: [],
  removed_tags: [],
})

const tagRow = t => ({
  form_id: t.form_id,
  form_name: t.form_name ?? '',
  project_id: t.project_id ?? '',
  assign_to_user_id: t.assign_to_user_id ?? '',
  leads: t.leads ?? 0,
  unrouted_leads: t.unrouted_leads ?? 0,
})

// trim, lower case, collapse inner spaces — the server's rule
const normaliseTag = tag => tag.trim().replace(/\s+/g, ' ').toLowerCase()

// reset on every open: the card's settings change under it after each save
watch(() => props.show, (open) => {
  if (!open) return

  const s = props.card?.settings ?? {}

  form.clearErrors()
  form.defaults({
    default_project_id: s.default_project_id ?? '',
    assign_to_user_id: s.assign_to_user_id ?? '',
    is_active: props.card?.is_active ?? false,
    tags: (props.card?.tags ?? []).map(tagRow),
    removed_tags: [],
  })
  form.reset()
  newTag.value = ''
  newTagError.value = ''
})

/* ---------------- the tag table ---------------- */

const newTag = ref('')
const newTagError = ref('')

const addTag = () => {
  const label = newTag.value.trim().replace(/\s+/g, ' ')
  const key = normaliseTag(label)
  newTagError.value = ''
  if (!key) return
  if (key.includes(',')) {
    newTagError.value = 'Add one tag at a time — a tag cannot contain a comma.'
    return
  }
  if (form.tags.some(t => t.form_id === key)) {
    newTagError.value = 'That tag is already in the list.'
    return
  }
  form.tags.push(tagRow({ form_id: key, form_name: label }))
  form.removed_tags = form.removed_tags.filter(r => r !== key)
  newTag.value = ''
}

// only a tag no lead has arrived with; nothing is deleted until Save
const removing = ref(null)

const removingLabel = computed(() => {
  const t = form.tags[removing.value]
  return t ? (t.form_name || t.form_id) : ''
})

const confirmRemove = () => {
  const [removed] = form.tags.splice(removing.value, 1)
  form.removed_tags.push(removed.form_id)
  removing.value = null
}

// next tick: see FacebookSettingsModal — Escape reaches both Modals at once
const cancelRemove = () => setTimeout(() => (removing.value = null))

const closeSettings = () => { if (removing.value === null) emit('close') }

// a tag that gained a lead while the modal was open is refused by the server
const removeError = computed(() =>
  Object.entries(form.errors).find(([k]) => k.startsWith('removed_tags.'))?.[1] ?? '')

const unmappedCount = computed(() => form.tags.filter(t => !t.project_id).length)

const submit = () => {
  form
    .transform(data => ({
      ...data,
      tags: data.tags.map(({ leads, unrouted_leads, ...t }) => ({
        ...t,
        project_id: t.project_id || null,
        assign_to_user_id: t.assign_to_user_id || null,
      })),
    }))
    .put(route('integrations.update', { provider: props.card.provider }), {
      preserveScroll: true,
      onSuccess: () => emit('close'),
    })
}
</script>

<template>
  <Modal :show="show" title="WhatsApp (11za)" max-width="max-w-3xl" @close="closeSettings">
    <form id="wa-settings" class="space-y-6" @submit.prevent="submit">

      <!-- ---------- where the leads go ---------- -->
      <section class="space-y-4">
        <header>
          <h4 class="text-sm font-semibold text-slate-900">Where these leads land</h4>
        </header>

        <div class="grid gap-4 sm:grid-cols-2">
          <FormField label="Default project" required :error="form.errors.default_project_id"
                     hint="Where WhatsApp leads go when no 11za tag below matches.">
            <select v-model="form.default_project_id">
              <option value="">Choose a project</option>
              <option v-for="p in options.projects" :key="p.id" :value="p.id">{{ p.name }}</option>
            </select>
          </FormField>

          <!-- telecallers only, for the same reason as on the Facebook modal -->
          <FormField label="Assign leads to" required :error="form.errors.assign_to_user_id"
                     hint="A telecaller. They get the lead and a follow-up due immediately.">
            <select v-model="form.assign_to_user_id">
              <option value="">Choose a telecaller</option>
              <option v-for="u in options.users" :key="u.id" :value="u.id">{{ u.label }}</option>
            </select>
          </FormField>
        </div>

        <!-- ---------- projects by 11za tag ---------- -->
        <div class="space-y-3">
          <h5 class="text-sm font-semibold text-slate-800">
            Projects by 11za tag
            <span v-if="unmappedCount" class="ml-1 rounded-full bg-amber-50 px-2 py-0.5 text-[11px] font-semibold text-amber-800">
              {{ unmappedCount }} without a project
            </span>
          </h5>

          <p class="info-box">
            Leads whose 11za tag matches go to that project. A label is used only if you've added it
            here yourself.
          </p>

          <div v-for="(t, i) in form.tags" :key="t.form_id"
               class="rounded-lg border p-3"
               :class="t.project_id ? 'border-slate-200' : 'border-amber-200 bg-amber-50/40'">
            <div class="mb-2 flex items-start justify-between gap-2">
              <div class="min-w-0">
                <p class="text-sm font-medium text-slate-800">{{ t.form_name || t.form_id }}</p>
                <p v-if="t.leads" class="mt-0.5 text-[11px] text-slate-400">
                  {{ t.leads }} {{ t.leads === 1 ? 'lead' : 'leads' }} so far
                </p>
                <p v-if="form.errors[`tags.${i}.form_id`]" class="text-xs text-rose-600">
                  {{ form.errors[`tags.${i}.form_id`] }}
                </p>
                <p v-if="!t.project_id" class="mt-0.5 text-[11px] font-semibold text-amber-800">
                  Not mapped — goes to default project<template v-if="t.unrouted_leads">
                    · {{ t.unrouted_leads }} {{ t.unrouted_leads === 1 ? 'lead' : 'leads' }} went there</template>
                </p>
              </div>
              <button v-if="!t.leads" type="button" class="text-xs text-slate-400 hover:text-rose-600"
                      @click="removing = i">
                Remove
              </button>
            </div>

            <div class="grid gap-3 sm:grid-cols-2">
              <FormField label="Project" :error="form.errors[`tags.${i}.project_id`]">
                <select v-model="t.project_id">
                  <option value="">Not mapped — goes to default project</option>
                  <option v-for="p in options.projects" :key="p.id" :value="p.id">{{ p.name }}</option>
                </select>
              </FormField>
              <FormField label="Assign leads to" :error="form.errors[`tags.${i}.assign_to_user_id`]">
                <select v-model="t.assign_to_user_id">
                  <option value="">The telecaller above</option>
                  <option v-for="u in options.users" :key="u.id" :value="u.id">{{ u.label }}</option>
                </select>
              </FormField>
            </div>
          </div>

          <p v-if="removeError" class="text-xs text-rose-600">{{ removeError }}</p>

          <div>
            <div class="flex gap-2">
              <input v-model="newTag" type="text" placeholder="Tag exactly as in 11za, e.g. Tower B"
                     @keydown.enter.prevent="addTag" />
              <button type="button" class="btn-ghost flex-none !px-3 !text-xs" @click="addTag">Add tag</button>
            </div>
            <p v-if="newTagError" class="mt-1 text-xs text-rose-600">{{ newTagError }}</p>
          </div>
        </div>

        <label class="flex items-start gap-2.5 text-sm">
          <input v-model="form.is_active" type="checkbox" class="mt-0.5 h-4 w-4 flex-none" />
          <span>
            <span class="font-medium text-slate-800">Accept leads from WhatsApp</span>
            <span class="block text-xs text-slate-500">
              When off, deliveries from 11za are logged and discarded rather than imported.
            </span>
          </span>
        </label>
        <p v-if="form.errors.is_active" class="text-xs text-rose-600">{{ form.errors.is_active }}</p>
      </section>

      <!-- ---------- what they paste into 11za ---------- -->
      <section class="space-y-4 border-t border-slate-100 pt-5">
        <header>
          <h4 class="text-sm font-semibold text-slate-900">Paste these into 11za</h4>
          <p class="mt-0.5 text-xs text-slate-500">
            In 11za: Inbound Webhooks &gt; Add &gt; Customer Webhook. Paste this URL as API Url and this key as API Key.
          </p>
        </header>

        <CopyField label="API Url" :value="card.webhook?.url"
                   hint="Must be https and reachable from the internet." />

        <CopyField v-if="card.webhook?.api_key" label="API Key" :value="card.webhook.api_key"
                   hint="11za sends this with every delivery. It does not change." />

        <p v-else class="info-box">
          Save these settings once and the API key will appear here, ready to paste into 11za.
        </p>
      </section>
    </form>

    <template #footer>
      <button type="button" class="btn-ghost" @click="emit('close')">Cancel</button>
      <button type="submit" form="wa-settings" class="btn" :disabled="form.processing">
        {{ form.processing ? 'Saving…' : 'Save settings' }}
      </button>
    </template>

    <ConfirmDialog
      :show="removing !== null"
      :title="`Remove '${removingLabel}'?`"
      message="No lead has arrived with this tag yet. If 11za sends it later it comes back here, not mapped. The tag is removed when you save."
      confirm-text="Remove"
      @close="cancelRemove"
      @confirm="confirmRemove"
    />
  </Modal>
</template>
