<script setup>
import { watch } from 'vue'
import { useForm } from '@inertiajs/vue3'
import Modal from '@/Components/Modal.vue'
import FormField from '@/Components/FormField.vue'
import CopyField from '@/Components/CopyField.vue'

/*
 | 11za WhatsApp chatbot configuration.
 |
 | The same two halves as the Facebook modal: where the leads land, which the
 | admin chooses here, and the webhook URL and API key, which they copy into
 | 11za. There are no tokens to type — the API key is generated by the CRM on
 | the first save and stays the same after that.
 */
const props = defineProps({
  show: Boolean,
  card: Object,
  options: Object,
})

const emit = defineEmits(['close'])

const form = useForm({
  default_project_id: '',
  assign_to_user_id: '',
  is_active: false,
})

// reset on every open: the card's settings change under it after each save
watch(() => props.show, (open) => {
  if (!open) return

  const s = props.card?.settings ?? {}

  form.clearErrors()
  form.defaults({
    default_project_id: s.default_project_id ?? '',
    assign_to_user_id: s.assign_to_user_id ?? '',
    is_active: props.card?.is_active ?? false,
  })
  form.reset()
})

const submit = () => {
  form.put(route('integrations.update', { provider: props.card.provider }), {
    preserveScroll: true,
    onSuccess: () => emit('close'),
  })
}
</script>

<template>
  <Modal :show="show" title="WhatsApp (11za)" max-width="max-w-2xl" @close="emit('close')">
    <form id="wa-settings" class="space-y-6" @submit.prevent="submit">

      <!-- ---------- where the leads go ---------- -->
      <section class="space-y-4">
        <header>
          <h4 class="text-sm font-semibold text-slate-900">Where these leads land</h4>
        </header>

        <div class="grid gap-4 sm:grid-cols-2">
          <FormField label="Project" required :error="form.errors.default_project_id"
                     hint="Every WhatsApp lead is filed under this project.">
            <select v-model="form.default_project_id">
              <option value="">Choose a project</option>
              <option v-for="p in options.projects" :key="p.id" :value="p.id">{{ p.name }}</option>
            </select>
          </FormField>

          <!-- telecallers only, for the same reason as on the Facebook modal -->
          <FormField label="Assign leads to" required :error="form.errors.assign_to_user_id"
                     hint="A telecaller. They get the lead and a follow-up due immediately.">
            <select v-model="form.assign_to_user_id">
              <option value="">Choose a telecaller</option>
              <option v-for="u in options.users" :key="u.id" :value="u.id">{{ u.label }}</option>
            </select>
          </FormField>
        </div>

        <label class="flex items-start gap-2.5 text-sm">
          <input v-model="form.is_active" type="checkbox" class="mt-0.5 h-4 w-4 flex-none" />
          <span>
            <span class="font-medium text-slate-800">Accept leads from WhatsApp</span>
            <span class="block text-xs text-slate-500">
              When off, deliveries from 11za are logged and discarded rather than imported.
            </span>
          </span>
        </label>
        <p v-if="form.errors.is_active" class="text-xs text-rose-600">{{ form.errors.is_active }}</p>
      </section>

      <!-- ---------- what they paste into 11za ---------- -->
      <section class="space-y-4 border-t border-slate-100 pt-5">
        <header>
          <h4 class="text-sm font-semibold text-slate-900">Paste these into 11za</h4>
          <p class="mt-0.5 text-xs text-slate-500">
            In 11za: Inbound Webhooks &gt; Add &gt; Customer Webhook. Paste this URL as API Url and this key as API Key.
          </p>
        </header>

        <CopyField label="API Url" :value="card.webhook?.url"
                   hint="Must be https and reachable from the internet." />

        <CopyField v-if="card.webhook?.api_key" label="API Key" :value="card.webhook.api_key"
                   hint="11za sends this with every delivery. It does not change." />

        <p v-else class="info-box">
          Save these settings once and the API key will appear here, ready to paste into 11za.
        </p>
      </section>
    </form>

    <template #footer>
      <button type="button" class="btn-ghost" @click="emit('close')">Cancel</button>
      <button type="submit" form="wa-settings" class="btn" :disabled="form.processing">
        {{ form.processing ? 'Saving…' : 'Save settings' }}
      </button>
    </template>
  </Modal>
</template>
